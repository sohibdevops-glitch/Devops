    $SecretsToDelete | ForEach-Object -ThrottleLimit 10 -Parallel {
        try {
            # Run az command and suppress stderr so we can handle errors
            $result = az keyvault secret delete --name $_ --vault-name $using:Vault 2>&1

            if ($LASTEXITCODE -eq 0) {
                Write-Output "[$using:Vault] Secret '$_' deleted successfully. 🗑️"
            }
            elseif ($result -match "not found") {
                Write-Output "[$using:Vault] Secret '$_' not found ✅"
            }
            else {
                Write-Output "[$using:Vault] Secret '$_' deletion failed: $result"
            }
        }
        catch {
            Write-Output "[$using:Vault] Secret '$_' deletion error: $_"
        }
    }
}